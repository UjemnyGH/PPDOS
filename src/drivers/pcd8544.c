enum pcd_function {
  pcd_function_extendedInstruction  = 0x01,
  pcd_function_entryMode            = 0x02,
  pcd_function_powerDown            = 0x04
};

enum pcd_displayControl {
  pcd_displayControl_blank          = 0x00,
  pcd_displayControl_allOn          = 0x01,
  pcd_displayControl_normal         = 0x04,
  pcd_displayControl_inverted       = 0x05
};

enum pcd_instruction {
  pcd_instruction_displayControl    = 0x08,
  pcd_instruction_functionSet       = 0x20,
  pcd_instruction_setYAddress       = 0x40,
  pcd_instruction_setXAddress       = 0x80,
};

enum pcd_extendedInstruction {
  pcd_extendedInstruction_setTemp   = 0x04,
  pcd_extendedInstruction_setBias   = 0x10,
  pcd_extendedInstruction_setVop    = 0x80
};

